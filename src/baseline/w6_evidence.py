def _load_json(path: Path, label: str) -> dict[str, Any]:
    try:
        value = json.loads(path.read_bytes())
    except (OSError, json.JSONDecodeError) as exc:
        raise W6Hold(f"cannot load {label}: {exc}") from exc
    require(isinstance(value, dict), f"{label} is not a JSON object")
    return value


def contract_binding() -> dict[str, Any]:
    raw = CONTRACT_PATH.read_bytes()
    return {"path": str(CONTRACT_PATH.relative_to(REPO_ROOT)), "contract_id": CONTRACT_PREFIX + sha256_bytes(raw), "file_sha256": sha256_bytes(raw)}


def _binding(spec: tuple[Any, ...]) -> dict[str, Any]:
    name, rel, role, schema, id_field, prefix, scientific, provenance, needed, custody = spec
    path = REPO_ROOT / rel
    require(path.is_file(), f"required W6 artifact is missing: {rel}")
    raw = path.read_bytes()
    own_id = None
    if id_field is not None:
        payload = _load_json(path, name)
        require(payload.get("schema_version") == schema, f"{name} schema/version drift")
        require(payload.get("artifact_role") == role, f"{name} artifact role differs")
        own_id = payload.get(id_field)
        require(isinstance(own_id, str) and own_id.startswith(prefix), f"{name} own-artifact ID is missing or mistyped")
    file_sha256 = sha256_bytes(raw)
    if name in _W6_FROZEN_NORMATIVE_SHA256:
        allowed = {
            _W6_FROZEN_NORMATIVE_SHA256[name],
            _W7C_CURRENT_NORMATIVE_SHA256[name],
        }
        if file_sha256 == _W8_CURRENT_NORMATIVE_SHA256[name]:
            # AM-93 is an additive post-W7-C clarification.  Authenticate its
            # exact compatibility record before projecting back to the frozen
            # W6 index bytes; never accept a live hash by name alone.
            load_w8_spec_compatibility(REPO_ROOT)
            allowed.add(_W8_CURRENT_NORMATIVE_SHA256[name])
        require(
            file_sha256 in allowed,
            f"{name} is neither the frozen W6 nor an authenticated successor normative byte image",
        )
        file_sha256 = _W6_FROZEN_NORMATIVE_SHA256[name]
    return {
        "logical_name": name, "path": rel, "artifact_role": role,
        "schema_version": schema, "own_artifact_id_field": id_field,
        "own_artifact_id": own_id, "file_sha256": file_sha256,
        "scientific_role": scientific, "provenance_role": provenance,
        "immutable_or_frozen": True, "needed_again": needed, "custody_mode": custody,
    }


