def build_matrix(index: Mapping[str, Any] | None = None) -> dict[str, Any]:
    current = dict(index or build_index())
    entries = matrix_entries()
    counts = {status: sum(row["status"] == status for row in entries) for status in sorted(STATUSES)}
    body = {
        "schema_version": SCHEMA_VERSION, "artifact_role": "w6_a_requirement_status_matrix",
        "stage": STAGE, "terminal_w6_completion_published": False,
        "index_id": current["index_id"], "index_file_sha256": sha256_bytes(canonical(current)),
        "classification_vocabulary": sorted(STATUSES), "counts": counts, "entries": entries,
        "w6_hold": counts["W6_REQUIRED_AND_MISSING"] != 0,
    }
    return _identified(body, field="matrix_id", prefix=MATRIX_PREFIX)


