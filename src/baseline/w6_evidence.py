class W6Hold(RuntimeError):
    """A W6 evidence, identity, scope, or scientific-boundary violation."""


def require(condition: bool, message: str) -> None:
    if not condition:
        raise W6Hold(message)


def canonical(value: Any) -> bytes:
    return (json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True) + "\n").encode("ascii")


def sha256_bytes(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def _identified(body: Mapping[str, Any], *, field: str, prefix: str) -> dict[str, Any]:
    value = dict(body)
    value[field] = prefix + sha256_bytes(canonical(value))
    return value


def _verify_identity(value: Mapping[str, Any], *, field: str, prefix: str, label: str) -> None:
    claimed = value.get(field)
    require(isinstance(claimed, str) and claimed.startswith(prefix), f"{label} own-artifact ID is missing or mistyped")
    body = dict(value); body.pop(field, None)
    require(claimed == prefix + sha256_bytes(canonical(body)), f"{label} own-artifact ID content digest differs")


